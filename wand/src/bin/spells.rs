//! Neural-network spell recogniser.
//!
//! Streams motion from the MPU6050 into a rolling 90-sample window and runs a
//! quantised CNN over it on-device, printing the router action for whichever
//! spell it recognises. The model is trained by `train/train_spells.py` and
//! compiled into the firmware by MicroFlow's `model!` macro.
//!
//! Build with the model in place:
//!     cargo build --release --bin spells --features ml

#![no_std]
#![no_main]

use esp_backtrace as _;
use esp_hal::delay::Delay;
use esp_hal::i2c::master::{Config, I2c};
use esp_hal::time::{Duration, Instant};
use esp_println::{print, println};
use microflow::buffer::Buffer2D;
use microflow::model;

esp_bootloader_esp_idf::esp_app_desc!();

const MPU6050_ADDR: u8 = 0x68;
const REG_WHO_AM_I: u8 = 0x75;
const REG_PWR_MGMT_1: u8 = 0x6B;
const REG_CONFIG: u8 = 0x1A;
const REG_GYRO_CONFIG: u8 = 0x1B;
const REG_ACCEL_CONFIG: u8 = 0x1C;
const REG_ACCEL_XOUT_H: u8 = 0x3B;

/// Must match the model's input shape and the rate the training data was
/// recorded at: 90 samples at 100 Hz is a 0.9 s window. The network only sees
/// gestures shaped the way it was trained on, so none of these three can move
/// without retraining.
const WINDOW: usize = 90;
const CHANNELS: usize = 6;
const PERIOD_MS: u64 = 10;

/// Sensor ranges, matching capture.rs. A fast swipe runs off the end of the
/// default +-2 g and +-250 deg/s, and a clipped reading looks the same
/// whichever way the wand moved.
const ACCEL_CONFIG_8G: u8 = 0x10; // AFS_SEL = 2 -> +-8 g, 4096 LSB/g
const GYRO_CONFIG_1000DPS: u8 = 0x10; // FS_SEL = 2 -> +-1000 deg/s, 32.8 LSB/deg/s
/// Digital low-pass at 44 Hz: sampling at 100 Hz, the sensor's default 260 Hz
/// bandwidth would fold everything above 50 Hz back into the band the model
/// looks at.
const DLPF_44HZ: u8 = 0x03;

/// Raw counts -> g and deg/s. The same scaling the training script applies.
const ACCEL_LSB_PER_G: f32 = 4096.0;
const GYRO_LSB_PER_DPS: f32 = 32.8;

/// Minimum softmax probability before a spell is announced.
const CONFIDENCE: f32 = 0.80;
/// Samples to wait after casting before another spell can fire (~1.2 s), so one
/// gesture is not reported several times as it slides through the window, and
/// the return stroke has time to happen unnoticed.
const COOLDOWN: usize = 120;

/// How many times each spell is broadcast, and the gap between the copies.
/// The gap must stay well under the bridge's de-duplication window, and the
/// whole burst well under the cooldown, so repeats are never mistaken for a
/// second cast.
#[cfg(feature = "radio")]
const REPEATS: usize = 3;
#[cfg(feature = "radio")]
const REPEAT_GAP_MS: u32 = 15;

/// How many recent samples are used to tell whether the wand is moving.
const RECENT: usize = 12;
/// Average change per channel, per sample, that counts as the wand moving...
const ACTIVE_GATE: f32 = 2.0;
/// ...and the level it must drop back below for the movement to count as over.
/// Two thresholds rather than one so that a gesture passing briefly through the
/// middle of its swing does not read as having finished.
const QUIET_GATE: f32 = 0.8;

/// Class names, in the order the model outputs them. Generated by the training
/// script from the capture file names, so the two can never drift apart.
const LABELS: &str = include_str!("../../model/labels.txt");

#[model("model/spells.tflite")]
struct Spells;

/// The router action each spell maps to. Printed for now; the actual SSH and
/// iperf3 work happens on the host that reads these lines.
fn action_for(label: &str) -> &'static str {
    match label {
        "left" => "cycle to previous interface",
        "right" => "cycle to next interface",
        "up" => "turn on interface",
        "down" => "shutdown interface",
        "push" => "stress test interface (iperf3 UDP flood)",
        "circular" => "backup router config",
        _ => "no action",
    }
}

/// Broadcasts the spell so any listener on the channel picks it up. Using the
/// broadcast address avoids having to know the receiver's MAC.
#[cfg(feature = "radio")]
fn broadcast(esp_now: &mut esp_radio::esp_now::EspNow<'_>, spell: &str) {
    // Newline-terminated: the controller reads a line at a time.
    let mut frame = [0u8; 24];
    let name = spell.as_bytes();
    if name.len() + 1 > frame.len() {
        return;
    }
    frame[..name.len()].copy_from_slice(name);
    frame[name.len()] = b'\n';

    // Sent several times on purpose. An ESP-NOW broadcast is not acknowledged
    // and is never retried by the MAC layer, so a frame lost to a collision is
    // lost for good - and the sender still reports success, because all it
    // knows is that the frame went out. Channel 1 is shared with every 2.4 GHz
    // network within range, including the router being managed, so collisions
    // are ordinary rather than rare. Three copies a few milliseconds apart cost
    // nothing and have to be unlucky three times over; the bridge drops the
    // repeats so downstream only ever sees one cast.
    let delay = Delay::new();
    for i in 0..REPEATS {
        match esp_now.send(&esp_radio::esp_now::BROADCAST_ADDRESS, &frame[..name.len() + 1]) {
            // Waiting keeps the next send from starting before this one lands.
            Ok(waiter) => {
                if waiter.wait().is_err() {
                    println!("    (radio: send failed)");
                }
            }
            Err(_) => println!("    (radio: could not queue)"),
        }
        if i + 1 < REPEATS {
            delay.delay_millis(REPEAT_GAP_MS);
        }
    }
}

#[esp_hal::main]
fn main() -> ! {
    let peripherals = esp_hal::init(esp_hal::Config::default());
    let delay = Delay::new();

    let mut i2c = I2c::new(peripherals.I2C0, Config::default())
        .expect("Failed to create I2C")
        .with_sda(peripherals.GPIO12)
        .with_scl(peripherals.GPIO13);

    println!("=== Motion Spells (neural network) ===");

    // --- Radio ---
    // The scheduler must be running before the radio is initialised, and both
    // must be set up before the first transmission.
    #[cfg(feature = "radio")]
    let mut _wifi;
    #[cfg(feature = "radio")]
    let mut esp_now = {
        use esp_hal::interrupt::software::SoftwareInterruptControl;
        use esp_hal::timer::timg::TimerGroup;

        // The radio needs a heap under it. The reclaimed region is RAM the ROM
        // bootloader no longer needs once we are running, which would otherwise
        // sit unused.
        esp_alloc::heap_allocator!(#[esp_hal::ram(reclaimed)] size: 64 * 1024);
        esp_alloc::heap_allocator!(size: 36 * 1024);

        let timg0 = TimerGroup::new(peripherals.TIMG0);
        let sw_int = SoftwareInterruptControl::new(peripherals.SW_INTERRUPT);
        esp_rtos::start(timg0.timer0, sw_int.software_interrupt0);

        _wifi = esp_radio::wifi::WifiController::new(peripherals.WIFI, Default::default())
            .expect("wifi init failed");

        // Applying a config is what actually starts the interface: esp-radio
        // only calls esp_wifi_start() from set_config, and only when the mode
        // changes. Without this the radio never transmits - sends are accepted
        // and their completion callback fires, but nothing reaches the air.
        if let Err(e) = _wifi.set_config(&esp_radio::wifi::Config::Station(Default::default())) {
            println!("WARNING: could not start wifi: {:?}", e);
        }

        let esp_now = _wifi.esp_now();

        // ESP-NOW only reaches peers on the same channel, and the NodeMCU
        // bridge sits on channel 1.
        if esp_now.set_channel(1).is_err() {
            println!("WARNING: could not set radio channel");
        }
        println!("Radio up: broadcasting spells on channel 1");
        esp_now
    };

    // Radio self-test: three broadcasts at boot, so the link can be checked
    // without having to cast a gesture. If these do not appear on the bridge's
    // console, the problem is the radio, not the recogniser.
    #[cfg(feature = "radio")]
    for i in 0..3 {
        broadcast(&mut esp_now, "PING");
        println!("radio self-test {}/3 sent", i + 1);
        // Spaced wider than the bridge's de-duplication window, so all three
        // show up there rather than being folded into one.
        delay.delay_millis(700);
    }

    // Cast each spell once, for testing the link and everything downstream
    // without a gesture. Enabled by the `selftest` feature only.
    #[cfg(feature = "selftest")]
    {
        println!("SELFTEST: casting each spell in turn");
        for spell in ["LEFT", "RIGHT", "UP", "DOWN"] {
            delay.delay_millis(2500);
            println!(">>> {} (selftest)", spell);
            broadcast(&mut esp_now, spell);
        }
        println!("SELFTEST: done");
    }

    let mut who = [0u8; 1];
    match i2c.write_read(MPU6050_ADDR, &[REG_WHO_AM_I], &mut who) {
        Ok(_) => println!("Sensor OK (WHO_AM_I = {:#04x})", who[0]),
        Err(e) => {
            println!("ERROR: no answer from the sensor: {:?}", e);
            loop {}
        }
    }
    i2c.write(MPU6050_ADDR, &[REG_PWR_MGMT_1, 0x00])
        .expect("Failed to wake up MPU6050");
    delay.delay_millis(100);

    for (reg, value) in [
        (REG_ACCEL_CONFIG, ACCEL_CONFIG_8G),
        (REG_GYRO_CONFIG, GYRO_CONFIG_1000DPS),
        (REG_CONFIG, DLPF_44HZ),
    ] {
        i2c.write(MPU6050_ADDR, &[reg, value])
            .expect("Failed to configure MPU6050");
    }

    print!("Spells:");
    for label in LABELS.lines() {
        print!(" {}", label.trim());
    }
    println!("\nReady - cast away.\n");

    // Rolling window, oldest sample first. `head` is where the next one lands.
    let mut window = [[0.0f32; CHANNELS]; WINDOW];
    let mut head = 0usize;
    let mut filled = 0usize;
    let mut cooldown = 0usize;
    let mut moving = false;
    let mut peak = 0.0f32;

    // Sampling is paced against a deadline rather than by sleeping a fixed
    // amount at the end of each pass. Inference happens inside this loop, and
    // delaying afterwards would add its cost to the sample interval: the window
    // would quietly cover more time than the 0.9 s the model was trained on,
    // which is the kind of mismatch that shows up only as poor accuracy.
    let period = Duration::from_millis(PERIOD_MS);
    let mut deadline = Instant::now();
    let mut warned_overrun = false;
    let mut timed_inference = false;

    loop {
        // Whether this pass ran the network, so the deliberate pause that
        // causes is not mistaken for the sampler falling behind.
        let mut inferred = false;

        if let Some(sample) = read_motion(&mut i2c) {
            window[head] = sample;
            head = (head + 1) % WINDOW;
            filled = (filled + 1).min(WINDOW);
        }
        if cooldown > 0 {
            cooldown -= 1;
        }

        // Classify when the wand comes to rest, not while it is being swung.
        // Inference blocks sampling for tens of milliseconds, and running it
        // mid-swing would punch that hole straight through the window being
        // classified - the gesture would reach the model with a chunk of itself
        // missing and the rest compressed in time. Waiting for the movement to
        // finish puts the pause where nothing is happening anyway, and by then
        // the whole gesture is sitting in the window.
        let activity = recent_activity(&window, head, filled);
        if activity >= ACTIVE_GATE && !moving {
            moving = true;
            peak = 0.0;
        }
        if moving && activity > peak {
            peak = activity;
        }

        if moving && activity < QUIET_GATE {
            moving = false;

            if filled == WINDOW && cooldown == 0 {
                inferred = true;
                // Unroll the ring buffer into chronological order, which is how
                // the model was trained to see it.
                let input = [Buffer2D::from_fn(|row, col| {
                    [window[(head + row) % WINDOW][col]]
                })];

                let started = Instant::now();
                let probs = Spells::predict(input);
                if !timed_inference {
                    // Reported once: it sets the ceiling on how often the
                    // network can run, and it is the first thing to look at if
                    // the sampling loop starts falling behind.
                    println!(
                        "Inference takes {} ms on this chip",
                        (Instant::now() - started).as_millis()
                    );
                    timed_inference = true;
                }

                let mut best = 0usize;
                for i in 1..probs.ncols() {
                    if probs[(0, i)] > probs[(0, best)] {
                        best = i;
                    }
                }
                let confidence = probs[(0, best)];
                let label = LABELS.lines().nth(best).unwrap_or("?").trim();

                if confidence >= CONFIDENCE && label != "negative" {
                    println!(
                        ">>> {:<9}-> {}   ({:.0}%)",
                        label.to_uppercase_ascii(),
                        action_for(label),
                        confidence * 100.0
                    );

                    // The controller expects upper case, matching its table.
                    #[cfg(feature = "radio")]
                    {
                        let mut upper = [0u8; 16];
                        let bytes = label.as_bytes();
                        let n = bytes.len().min(upper.len());
                        for i in 0..n {
                            upper[i] = bytes[i].to_ascii_uppercase();
                        }
                        if let Ok(text) = core::str::from_utf8(&upper[..n]) {
                            broadcast(&mut esp_now, text);
                        }
                    }

                    cooldown = COOLDOWN;
                } else {
                    // Movement that did not become a spell. Worth printing: it
                    // separates "the wand ignored you" from "the wand never
                    // noticed you", and the peak figure is what the two
                    // movement thresholds are set against.
                    println!(
                        "    (ignored: {} {:.0}%, peak {:.1})",
                        label,
                        confidence * 100.0,
                        peak
                    );
                }
            }
        }

        deadline += period;
        let now = Instant::now();
        if now > deadline {
            // Resynchronise rather than trying to catch up with a burst of
            // back-to-back reads. An inference pass is expected to land here
            // and is not worth reporting; anything else means the sampler is
            // genuinely too slow, and the window is being filled more slowly
            // than the training data was recorded.
            if !inferred && !warned_overrun {
                println!("WARNING: cannot keep up with {} ms sampling", PERIOD_MS);
                warned_overrun = true;
            }
            deadline = now;
        }
        while Instant::now() < deadline {}
    }
}

/// How much the wand has moved over the last few samples: the mean change per
/// channel from one sample to the next.
///
/// Measuring change rather than deviation from an average keeps this local -
/// it answers "is the wand moving right now", not "has anything happened
/// recently" - and a wand held still at any angle reads as zero, because
/// gravity is constant however the board is tilted.
fn recent_activity(window: &[[f32; CHANNELS]; WINDOW], head: usize, filled: usize) -> f32 {
    if filled < RECENT {
        return 0.0;
    }
    let mut total = 0.0;
    for k in 1..RECENT {
        // head is where the next sample lands, so the newest is one before it.
        let newer = window[(head + WINDOW - k) % WINDOW];
        let older = window[(head + WINDOW - k - 1) % WINDOW];
        for c in 0..CHANNELS {
            let d = newer[c] - older[c];
            total += if d < 0.0 { -d } else { d };
        }
    }
    total / ((RECENT - 1) * CHANNELS) as f32
}

/// Reads accel XYZ and gyro XYZ in one burst, scaled to g and deg/s.
fn read_motion(i2c: &mut I2c<'_, esp_hal::Blocking>) -> Option<[f32; CHANNELS]> {
    let mut buf = [0u8; 14];
    i2c.write_read(MPU6050_ADDR, &[REG_ACCEL_XOUT_H], &mut buf).ok()?;
    let v = |hi: usize| i16::from_be_bytes([buf[hi], buf[hi + 1]]) as f32;
    Some([
        v(0) / ACCEL_LSB_PER_G,
        v(2) / ACCEL_LSB_PER_G,
        v(4) / ACCEL_LSB_PER_G,
        v(8) / GYRO_LSB_PER_DPS,
        v(10) / GYRO_LSB_PER_DPS,
        v(12) / GYRO_LSB_PER_DPS,
    ])
}

/// Tiny helper so labels print in capitals without needing `alloc`.
trait UpperAscii {
    fn to_uppercase_ascii(&self) -> UpperStr<'_>;
}
impl UpperAscii for str {
    fn to_uppercase_ascii(&self) -> UpperStr<'_> {
        UpperStr(self)
    }
}
struct UpperStr<'a>(&'a str);
impl core::fmt::Display for UpperStr<'_> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        for c in self.0.chars() {
            write!(f, "{}", c.to_ascii_uppercase())?;
        }
        Ok(())
    }
}
