//! Neural-network spell recogniser.
//!
//! Streams motion from the MPU6050 into a rolling 128-sample window and runs a
//! quantised CNN over it on-device, printing the router action for whichever
//! spell it recognises. The model is trained by `train/train_spells.py` and
//! compiled into the firmware by MicroFlow's `model!` macro.
//!
//! Build with the model in place:
//!     cargo build --release --bin spells --features ml

#![no_std]
#![no_main]

use esp_backtrace as _;
use esp_hal::delay::Delay;
use esp_hal::i2c::master::{Config, I2c};
use esp_println::{print, println};
use microflow::buffer::Buffer2D;
use microflow::model;

esp_bootloader_esp_idf::esp_app_desc!();

const MPU6050_ADDR: u8 = 0x68;
const REG_WHO_AM_I: u8 = 0x75;
const REG_PWR_MGMT_1: u8 = 0x6B;
const REG_ACCEL_XOUT_H: u8 = 0x3B;

/// Must match WINDOW and PERIOD_MS in capture.rs, and the model's input shape:
/// the network only sees gestures shaped the way it was trained on.
const WINDOW: usize = 128;
const CHANNELS: usize = 6;
const PERIOD_MS: u32 = 20;

/// Raw counts -> g and deg/s. The same scaling the training script applies.
const ACCEL_LSB_PER_G: f32 = 16384.0;
const GYRO_LSB_PER_DPS: f32 = 131.0;

/// Run the network every N samples rather than every sample: at 50 Hz this is
/// about 5 inferences a second, which is plenty for gestures and leaves the CPU
/// mostly idle.
const INFER_EVERY: usize = 10;
/// Minimum softmax probability before a spell is announced.
const CONFIDENCE: f32 = 0.80;
/// Samples to wait after casting before another spell can fire (~1.5 s), so one
/// gesture is not reported several times as it slides through the window.
const COOLDOWN: usize = 75;
/// Total motion energy the window must carry before it is worth classifying.
const MOTION_GATE: f32 = 1.5;

/// Class names, in the order the model outputs them. Generated by the training
/// script from the capture file names, so the two can never drift apart.
const LABELS: &str = include_str!("../../model/labels.txt");

#[model("model/spells.tflite")]
struct Spells;

/// The router action each spell maps to. Printed for now; the actual SSH and
/// iperf3 work happens on the host that reads these lines.
fn action_for(label: &str) -> &'static str {
    match label {
        "left" => "cycle to previous interface",
        "right" => "cycle to next interface",
        "up" => "turn on interface",
        "down" => "shutdown interface",
        "push" => "stress test interface (iperf3 UDP flood)",
        "circular" => "backup router config",
        _ => "no action",
    }
}

/// Broadcasts the spell so any listener on the channel picks it up. Using the
/// broadcast address avoids having to know the receiver's MAC.
#[cfg(feature = "radio")]
fn broadcast(esp_now: &mut esp_radio::esp_now::EspNow<'_>, spell: &str) {
    // Newline-terminated: the controller reads a line at a time.
    let mut frame = [0u8; 24];
    let name = spell.as_bytes();
    if name.len() + 1 > frame.len() {
        return;
    }
    frame[..name.len()].copy_from_slice(name);
    frame[name.len()] = b'\n';

    match esp_now.send(&esp_radio::esp_now::BROADCAST_ADDRESS, &frame[..name.len() + 1]) {
        // Waiting keeps the next send from starting before this one lands.
        Ok(waiter) => {
            if waiter.wait().is_err() {
                println!("    (radio: send failed)");
            }
        }
        Err(_) => println!("    (radio: could not queue)"),
    }
}

#[esp_hal::main]
fn main() -> ! {
    let peripherals = esp_hal::init(esp_hal::Config::default());
    let delay = Delay::new();

    let mut i2c = I2c::new(peripherals.I2C0, Config::default())
        .expect("Failed to create I2C")
        .with_sda(peripherals.GPIO12)
        .with_scl(peripherals.GPIO13);

    println!("=== Motion Spells (neural network) ===");

    // --- Radio ---
    // The scheduler must be running before the radio is initialised, and both
    // must be set up before the first transmission.
    #[cfg(feature = "radio")]
    let mut _wifi;
    #[cfg(feature = "radio")]
    let mut esp_now = {
        use esp_hal::interrupt::software::SoftwareInterruptControl;
        use esp_hal::timer::timg::TimerGroup;

        // The radio needs a heap under it. The reclaimed region is RAM the ROM
        // bootloader no longer needs once we are running, which would otherwise
        // sit unused.
        esp_alloc::heap_allocator!(#[esp_hal::ram(reclaimed)] size: 64 * 1024);
        esp_alloc::heap_allocator!(size: 36 * 1024);

        let timg0 = TimerGroup::new(peripherals.TIMG0);
        let sw_int = SoftwareInterruptControl::new(peripherals.SW_INTERRUPT);
        esp_rtos::start(timg0.timer0, sw_int.software_interrupt0);

        _wifi = esp_radio::wifi::WifiController::new(peripherals.WIFI, Default::default())
            .expect("wifi init failed");

        // Applying a config is what actually starts the interface: esp-radio
        // only calls esp_wifi_start() from set_config, and only when the mode
        // changes. Without this the radio never transmits - sends are accepted
        // and their completion callback fires, but nothing reaches the air.
        if let Err(e) = _wifi.set_config(&esp_radio::wifi::Config::Station(Default::default())) {
            println!("WARNING: could not start wifi: {:?}", e);
        }

        let esp_now = _wifi.esp_now();

        // ESP-NOW only reaches peers on the same channel, and the NodeMCU
        // bridge sits on channel 1.
        if esp_now.set_channel(1).is_err() {
            println!("WARNING: could not set radio channel");
        }
        println!("Radio up: broadcasting spells on channel 1");
        esp_now
    };

    // Radio self-test: three broadcasts at boot, so the link can be checked
    // without having to cast a gesture. If these do not appear on the bridge's
    // console, the problem is the radio, not the recogniser.
    #[cfg(feature = "radio")]
    for i in 0..3 {
        broadcast(&mut esp_now, "PING");
        println!("radio self-test {}/3 sent", i + 1);
        delay.delay_millis(400);
    }

    let mut who = [0u8; 1];
    match i2c.write_read(MPU6050_ADDR, &[REG_WHO_AM_I], &mut who) {
        Ok(_) => println!("Sensor OK (WHO_AM_I = {:#04x})", who[0]),
        Err(e) => {
            println!("ERROR: no answer from the sensor: {:?}", e);
            loop {}
        }
    }
    i2c.write(MPU6050_ADDR, &[REG_PWR_MGMT_1, 0x00])
        .expect("Failed to wake up MPU6050");
    delay.delay_millis(100);

    print!("Spells:");
    for label in LABELS.lines() {
        print!(" {}", label.trim());
    }
    println!("\nReady - cast away.\n");

    // Rolling window, oldest sample first. `head` is where the next one lands.
    let mut window = [[0.0f32; CHANNELS]; WINDOW];
    let mut head = 0usize;
    let mut filled = 0usize;
    let mut since_infer = 0usize;
    let mut cooldown = 0usize;

    loop {
        if let Some(sample) = read_motion(&mut i2c) {
            window[head] = sample;
            head = (head + 1) % WINDOW;
            filled = (filled + 1).min(WINDOW);
            since_infer += 1;
        }
        if cooldown > 0 {
            cooldown -= 1;
        }

        let ready = filled == WINDOW && since_infer >= INFER_EVERY && cooldown == 0;
        if ready {
            since_infer = 0;

            // Skip a window that holds no real movement. The negative class
            // would catch it anyway, but this avoids the work entirely.
            if motion_energy(&window) >= MOTION_GATE {
                // Unroll the ring buffer into chronological order, which is how
                // the model was trained to see it.
                let input = [Buffer2D::from_fn(|row, col| {
                    [window[(head + row) % WINDOW][col]]
                })];

                let probs = Spells::predict(input);

                let mut best = 0usize;
                for i in 1..probs.ncols() {
                    if probs[(0, i)] > probs[(0, best)] {
                        best = i;
                    }
                }
                let confidence = probs[(0, best)];
                let label = LABELS.lines().nth(best).unwrap_or("?").trim();

                if confidence >= CONFIDENCE && label != "negative" {
                    println!(
                        ">>> {:<9}-> {}   ({:.0}%)",
                        label.to_uppercase_ascii(),
                        action_for(label),
                        confidence * 100.0
                    );

                    // The controller expects upper case, matching its table.
                    #[cfg(feature = "radio")]
                    {
                        let mut upper = [0u8; 16];
                        let bytes = label.as_bytes();
                        let n = bytes.len().min(upper.len());
                        for i in 0..n {
                            upper[i] = bytes[i].to_ascii_uppercase();
                        }
                        if let Ok(text) = core::str::from_utf8(&upper[..n]) {
                            broadcast(&mut esp_now, text);
                        }
                    }

                    cooldown = COOLDOWN;
                }
            }
        }

        delay.delay_millis(PERIOD_MS);
    }
}

/// Rough "how much is happening" measure: mean absolute deviation from the
/// window's own average, so a board resting at any angle still reads as calm.
fn motion_energy(window: &[[f32; CHANNELS]; WINDOW]) -> f32 {
    let mut mean = [0.0f32; CHANNELS];
    for sample in window.iter() {
        for c in 0..CHANNELS {
            mean[c] += sample[c];
        }
    }
    for m in mean.iter_mut() {
        *m /= WINDOW as f32;
    }

    let mut energy = 0.0;
    for sample in window.iter() {
        for c in 0..CHANNELS {
            let d = sample[c] - mean[c];
            energy += if d < 0.0 { -d } else { d };
        }
    }
    energy / (WINDOW * CHANNELS) as f32
}

/// Reads accel XYZ and gyro XYZ in one burst, scaled to g and deg/s.
fn read_motion(i2c: &mut I2c<'_, esp_hal::Blocking>) -> Option<[f32; CHANNELS]> {
    let mut buf = [0u8; 14];
    i2c.write_read(MPU6050_ADDR, &[REG_ACCEL_XOUT_H], &mut buf).ok()?;
    let v = |hi: usize| i16::from_be_bytes([buf[hi], buf[hi + 1]]) as f32;
    Some([
        v(0) / ACCEL_LSB_PER_G,
        v(2) / ACCEL_LSB_PER_G,
        v(4) / ACCEL_LSB_PER_G,
        v(8) / GYRO_LSB_PER_DPS,
        v(10) / GYRO_LSB_PER_DPS,
        v(12) / GYRO_LSB_PER_DPS,
    ])
}

/// Tiny helper so labels print in capitals without needing `alloc`.
trait UpperAscii {
    fn to_uppercase_ascii(&self) -> UpperStr<'_>;
}
impl UpperAscii for str {
    fn to_uppercase_ascii(&self) -> UpperStr<'_> {
        UpperStr(self)
    }
}
struct UpperStr<'a>(&'a str);
impl core::fmt::Display for UpperStr<'_> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        for c in self.0.chars() {
            write!(f, "{}", c.to_ascii_uppercase())?;
        }
        Ok(())
    }
}
